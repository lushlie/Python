#arithmetic operators - simple calculations.
x = 90
y = 5
print(x + y)
print(x - y)
print(x * y) #multiple
print(x / y) #divide
print(x % y) #modulus returns remainder of /
print()

#comparison operators - compair values and return boolean.
print(x > y)
print(x < y)
print(x >= y)
print(x <= y)
print(x == y)  # equal
print(x != y)  # not equal to
print()

#assignment operators - store value in variable.
number = 78
print(number)

#operator precedence - like bodmas in math hs
number += 2
print(number)
print()

#logical operators - and, or, not (multiple).
print(30 > 20 and 56 == 10 ) #if any false all false
print(30 > 20 or 56 == 10 ) #if any true all true
print( not(30 > 20 and  56 == 10 )) # opposite


